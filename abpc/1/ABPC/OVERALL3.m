clear all
L = 10^(0.5/10);        %系统损耗 
k = 1.38*10^(-23);      %玻尔兹曼常数
F = 10^(0.5/10);        %噪声系数
B = 0.5*10^6;           %频谱宽度
T = 290;                %系统温度
Gpbest=10^3*[   3.4731    3.4731    3.4731    3.4731
    3.4536    3.4536    3.4536    3.4536
    3.4428    3.4428    3.4428    3.4428
    3.4930    3.4930    3.4930    3.4930];
Gabest=10^3*[  2.8051    2.9449    4.2501         0
    2.9542    2.7886         0    4.2572
    4.2568         0    2.7812    2.9620
         0    4.2513    2.9628    2.7859];
G=10^2*[28.22	29.63	42.76   0
29.82	28.14  0	42.97
42.96  0	28.07	29.89
0   42.77	29.81	28.03];
lamda = repmat(0.04,4,4);
sigma = [10 10 10 10
        10 10 10 10
        10 10 10 10
        10 10 10 10];
Tx=[20,30,50,60];
Ty=[40,40,40,40];
%z=[20,20,20,20];
Rx=[20,30,50,60];
Ry=[0,0,0,0];
%Tz=[0,0,0,0];
for i=1:4
    for j=1:4
    R(i,j)=((Tx(j)-Rx(i)).^2+(Ty(j)-Ry(i)).^2)^0.5;    
    end
end
SNR = (Gpbest.*Gabest.^2.*lamda.^2.*sigma)./(4^3*pi^3*L*k*F*B*T.*R.^4.*10^12);   %信噪比
P=(SNR.*4^3*pi.^3*L*k*F*B*T.*R.^4.*10^12)./(G.^2.*lamda.^2.*sigma);
for i=1:4
    for j=1:4
        if isnan(P(i,j))
            P(i,j)=0;
        end
    end
end
PTOTAL=sum(P,1);
disp(PTOTAL)
