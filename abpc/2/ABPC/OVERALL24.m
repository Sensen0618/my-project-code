clear all
L = 10^(0.5/10);        %系统损耗 
k = 1.38*10^(-23);      %玻尔兹曼常数
F = 10^(0.5/10);        %噪声系数
B = 0.5*10^6;           %频谱宽度
T = 290;                %系统温度
Gpbest=10000*[ 0.3513    0.8549    0.4195    1.2178
    0.1311    0.2502    0.0813    0.4063
    0.3504    0.6100    0.2101    0.7210
    0.6403    0.8427    0.2578    0.7311];
Gabest=1000*[  1.2353    3.0066    1.4752    4.2829
    1.5088    2.8793    0.9356    4.6763
    1.8525    3.2249    1.1107    3.8118
    2.5902    3.4093    1.0428    2.9577];
G=100*[12.8151   31.1906   15.3038   44.4310
   15.0142   28.6521    9.3102   46.5342
   18.8604   32.8329   11.3081   38.8081
   26.3182   34.6408   10.5956   30.0523];
lamda = repmat(0.04,4,4);
sigma = [10 10 10 10
        10 10 10 10
        10 10 10 10
        10 10 10 10];
Tx=[-10,20,40,70];
Ty=[40,70,40,60];
% z=[20,20,20,20];
Rx=[10,20,25,40];
Ry=[0,20,5,0];
for i=1:4
    for j=1:4
    R(i,j)=((Tx(j)-Rx(i)).^2+(Ty(j)-Ry(i)).^2)^0.5;    
    end
end
SNR = (Gpbest.*Gabest.*lamda.^2.*sigma)./(4^3*pi^3*L*k*F*B*T.*R.^4.*10^12);   %信噪比
P=(SNR.*4^3*pi.^3*L*k*F*B*T.*R.^4.*10^12)./(G.*lamda.^2.*sigma);
for i=1:4
    for j=1:4
        if isnan(P(i,j))
            P(i,j)=0;
        end
    end
end
PTOTAL=sum(P,"all");
disp(PTOTAL)
pppp=sum(P,2);