F = 10^(0.5/10);        %噪声系数
B = 0.5*10^6;           %频谱宽度
T = 290;                %系统温度
Gpbest=10^3*[  8.4722    8.4722    8.4722    8.4722
    6.5218    6.5218    6.5218    6.5218
    6.5121    6.5121    6.5121    6.5121
    8.5056    8.5056    8.5056    8.5056];
Gabest=10^3*[1.8183 1.9351 2.7420 3.5046
    2.1847 2.0830 2.5505 3.1818
    3.1892 2.5344 2.0796 2.1969
    3.5159 2.7383 1.9190 1.8268];
G=100*[18.83	20.04	28.40	36.30
22.03	21.00	25.72	32.08
32.16	25.55	20.97	22.15
36.42	28.37	19.88	18.92];
lamda = repmat(0.04,4,4);
sigma = [10 10 10 10
        10 10 10 10
        10 10 10 10
        10 10 10 10];
Tx=[20,30,50,60];
Ty=[40,40,40,40];
%z=[20,20,20,20];
Rx=[20,30,50,60];
Ry=[0,0,0,0];
%Tz=[0,0,0,0];
for i=1:4
    for j=1:4
    R(i,j)=((Tx(j)-Rx(i)).^2+(Ty(j)-Ry(i)).^2)^0.5;    
    end
end
SNR = (Gpbest.*Gabest.^2.*lamda.^2.*sigma)./(4^3*pi^3*L*k*F*B*T.*R.^4.*10^12);   %信噪比
P=(SNR.*4^3*pi.^3*L*k*F*B*T.*R.^4.*10^12)./(G.^2.*lamda.^2.*sigma);
for i=1:4
    for j=1:4
        if isnan(P(i,j))
            P(i,j)=0;
        end
    end
end
PTOTAL=sum(P,"all");
