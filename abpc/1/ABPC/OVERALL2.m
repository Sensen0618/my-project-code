clc
clear all
L = 10^(0.5/10);        %系统损耗 
k = 1.38*10^(-23);      %玻尔兹曼常数
F = 10^(0.5/10);        %噪声系数
B = 0.5*10^6;           %频谱宽度
T = 290;                %系统温度
Gpbest=[ 1075.6  1075.6         1075.6       1075.6
        1081.6  1081.6        1081.6       1081.6
        1080.8     1080.8    1080.8   1080.8 
        1076.5       1076.5  1076.5  1076.5];
Gabest=10^3*[4.8388    5.1612         0         0
    5.1616    4.8384         0         0
         0         0    4.8356    5.1644
         0         0    5.1640    4.8360];
G=100*[48.77	52.02 0 0
52.02	48.77   0   0
0 0  48.74	52.05
0  0  52.05	48.74];
lamda = repmat(0.04,4,4);
sigma = [10 10 10 10
        10 10 10 10
        10 10 10 10
        10 10 10 10];
Tx=[20,30,50,60];
Ty=[40,40,40,40];
%z=[20,20,20,20];
Rx=[20,30,50,60];
Ry=[0,0,0,0];
%Tz=[0,0,0,0];
for i=1:4
    for j=1:4
    R(i,j)=((Tx(j)-Rx(i)).^2+(Ty(j)-Ry(i)).^2)^0.5;    
    end
end
SNR = (Gpbest.*Gabest.^2.*lamda.^2.*sigma)./(4^3*pi^3*L*k*F*B*T.*R.^4.*10^12);   %信噪比
P=(SNR.*4^3*pi.^3*L*k*F*B*T.*R.^4.*10^12)./(G.^2.*lamda.^2.*sigma);
for i=1:4
    for j=1:4
        if isnan(P(i,j))
            P(i,j)=0;
        end
    end
end
PTOTAL=sum(P,"all");
disp(PTOTAL)
qqqq=sum(P,2);