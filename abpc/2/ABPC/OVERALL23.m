F = 10^(0.5/10);        %噪声系数
B = 0.5*10^6;           %频谱宽度
T = 290;                %系统温度
Gpbest=1000*[  1.9478    5.0843    2.5533         0
    1.0996    2.0805         0    3.3900
    2.2888         0    1.3622    4.7344
         0    5.9905    1.8049    5.1507];
Gabest=1000*[2.0320    5.3042    2.6637         0
    1.6736    3.1667         0    5.1597
    2.7295         0    1.6245    5.6460
         0    4.6273    1.3941    3.9786];
G=100*[20.6167	53.8139	27.0247 0
   16.9065 	31.9896	0 52.1227
     27.3470 0 16.2759	56.5675
     0 46.4654 	13.9990	39.9514];
lamda = repmat(0.04,4,4);
sigma = [10 10 10 10
        10 10 10 10
        10 10 10 10
        10 10 10 10];
Tx=[-10,20,40,70];
Ty=[40,70,40,60];
% z=[20,20,20,20];
Rx=[10,20,25,40];
Ry=[0,20,5,0];
for i=1:4
    for j=1:4
    R(i,j)=((Tx(j)-Rx(i)).^2+(Ty(j)-Ry(i)).^2)^0.5;    
    end
end
SNR = (Gpbest.*Gabest.*lamda.^2.*sigma)./(4^3*pi^3*L*k*F*B*T.*R.^4.*10^12);   %信噪比
P=(SNR.*4^3*pi.^3*L*k*F*B*T.*R.^4.*10^12)./(G.*lamda.^2.*sigma);
for i=1:4
    for j=1:4
        if isnan(P(i,j))
            P(i,j)=0;
        end
    end
end
PTOTAL=sum(P,"all");
